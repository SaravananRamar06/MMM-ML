         EPN = E**EN
         HRD = A - B*EPN
         BASE = HRD*(1.D0+C*RLN)*(1.D0-TM)*(GM/G0)**Q*(RHO/RHO0)**R
         IF (BASE .LE. 0.D0 .OR. HRD .LE. 0.D0) THEN
            IERR = 1
