            D2(I) = (1.D0-H2(I)**2)*D2(I)
            DEL = DEL + W3(I,K)*H2(I)
            DDL = DDL + W3(I,K)*D2(I)
         END DO
         SUML = SUML + LOG(BASE) + DEL
         SUMD = SUMD + DLB + DDL
      END DO
