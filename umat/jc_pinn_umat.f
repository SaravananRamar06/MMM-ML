            RETURN
         END IF
         DLB = -B*EN*EPN/(E*HRD)
C        ---- correction network and d delta/de -----------------------
         DO I = 1, NH
            S = B1(I,K)
            DO J = 1, NI
               S = S + W1(I,J,K)*Z(J)
            END DO
            H1(I) = TANH(S)
            D1(I) = (1.D0-H1(I)**2)*W1(I,NI,K)/XS(NI)
