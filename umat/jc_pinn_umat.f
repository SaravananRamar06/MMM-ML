C              2 = T, rate, density or G outside the data range
C              4 = 200 < T <= 300 degC (no data, unvalidated)
C    4  NITER  Newton iterations in the last increment
C
C  Units: MPa, degC, 1/s, kg/m3 (inferred from the data, open
C  question Q1). The data are simulations, not experiments; nothing
C  above 200 degC is validated. Softening (H < 0) localises: results
C  are mesh dependent beyond the stress peak.
