      IF (NDI .NE. 3) THEN
         INTV(1) = NDI
         CALL STDB_ABQERR(-3, 'JC-PINN UMAT: NDI = %I is not '//
     1    'supported (plane stress). Use 3D, plane strain or '//
     2    'axisymmetric elements.', INTV, REALV, CHARV)
         CALL XIT
      END IF
