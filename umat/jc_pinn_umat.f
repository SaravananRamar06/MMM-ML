C  (3D, plane strain, axisymmetric). Plane stress is rejected.
C
C  PROPS (NPROPS >= 6, 7 optional)
C    1  T      temperature, degC (used when PROPS(6) = 0)
C    2  RATE   strain rate, 1/s (fixed condition, as in the data)
C    3  RHO    density, kg/m3 (porosity phi = 1 - RHO/2700)
C    4  G      shear modulus, MPa (model input; also elastic G)
C    5  NU     Poisson's ratio (ASSUMED, not in the data; e.g. 0.33)
C    6  ITEMP  0 = use PROPS(1); 1 = use field TEMP+DTEMP
C    7  GEL    optional elastic shear modulus, MPa (0 = use PROPS(4))
