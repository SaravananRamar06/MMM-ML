#!/usr/bin/env python3
"""ANSYS Engineering Data Material Bridge (Template / Unvalidated Placeholder).

Generates tabular stress-strain cards and APDL command snippets from the
trained Svm query MLP ensemble for integration with ANSYS Workbench / Mechanical.

IMPORTANT SCIENTIFIC & MODELLING CAVEATS:
1. UNTESTED PLACEHOLDER: This bridge is a formatting template prepared ahead
   of inspecting the teammate's actual ANSYS FEA bracket model, boundary conditions,
   and material constitutive laws.
2. TOTAL STRAIN vs PLASTIC STRAIN: The underlying dataset provides operational
   axial strain E11 and equivalent stress Svm. If the receiving ANSYS material model
   (e.g., Multilinear Isotropic Hardening, TB,MISO) requires plastic strain, the
   user must provide a confirmed Young's modulus E to evaluate:
       epsilon_pl = max(0.0, epsilon_total - sigma / E)
   This script preserves raw total strain by default unless an explicit Young's
   modulus is supplied with --youngs-modulus.
3. NO FABRICATED LINEAR ELASTIC ORIGIN: The raw simulation curves begin at
   E11 ≈ 1e-6 with stresses already at 130–160 MPa. The dataset contains no
   linear-elastic origin or slope. This bridge does NOT invent synthetic zero-origin
   data points or unverified elastic moduli.
4. UNITS: Stress values are assumed MPa, strain is dimensionless (mm/mm), temperature
   is °C, and strain rate is 1/s, consistent with project disclosures.

Usage:
  .venv/bin/python tools/ansys_material_bridge.py --temperature 100 --rate 1e-4 --density 2619 --G 24541 --format csv --output material.csv
  .venv/bin/python tools/ansys_material_bridge.py --temperature 30 --rate 1e-3 --format apdl --output material.mac
"""
import argparse
import os
import sys
from pathlib import Path
import numpy as np

# Add project root and src to path
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from data import STRAIN_GRID  # noqa: E402
from predict import model_path, warnings_for  # noqa: E402
import joblib  # noqa: E402

DISCLOSURE_BANNER = """! ==============================================================================
! ANSYS MATERIAL CARD EXPORT (UNTESTED TEMPLATE / PLACEHOLDER)
! Generated by MMM-ML Svm Query MLP Model
! CAVEATS:
! 1. Model predicts operational total strain (E11) vs equivalent stress (Svm).
! 2. Raw training data begins at E11 ~ 1e-6 (stress ~130-160 MPa); linear elastic
!    origin (E, nu) is not in the data and is not fabricated here.
! 3. Verify receiving material model requirements with teammate FEA bracket model.
! =============================================================================="""


def predict_curve(temperature, rate, density=2700.0, G=25300.0, target="Svm"):
    """Query the trained MLP ensemble for a continuous 120-point curve."""
    path = model_path("mlp", target)
    if not path.exists():
        raise FileNotFoundError(f"Trained model artifact not found: {path}")
    model = joblib.load(path)
    
    log_rate = np.log10(rate)
    X = np.array([[temperature, log_rate, density, G]])
    stress = model.predict(X)[0]
    return STRAIN_GRID, stress


def format_tabular_csv(strains, stresses, youngs_modulus=None):
    """Format as CSV table for ANSYS Engineering Data import."""
    lines = [
        "# ANSYS Engineering Data Tabular Stress-Strain Table",
        "# Status: Untested template pending teammate ANSYS model verification",
    ]
    if youngs_modulus:
        lines.append(f"# Plastic strain calculated using Young's Modulus E = {youngs_modulus:g} MPa")
        lines.append("Plastic Strain [mm mm^-1],Stress [MPa]")
        for eps, sig in zip(strains, stresses):
            eps_pl = max(0.0, eps - sig / youngs_modulus)
            lines.append(f"{eps_pl:.8e},{sig:.6f}")
    else:
        lines.append("# Operational Total Strain E11 vs Svm Equivalent Stress (Raw Surrogate Output)")
        lines.append("Total Strain [mm mm^-1],Stress [MPa]")
        for eps, sig in zip(strains, stresses):
            lines.append(f"{eps:.8e},{sig:.6f}")
    return "\n".join(lines) + "\n"


def format_apdl_snippet(strains, stresses, mat_id=1, youngs_modulus=None, temperature=None):
    """Format as APDL command snippet (TB,MISO or TB,PLAS)."""
    lines = [
        DISCLOSURE_BANNER,
        f"/PREP7",
        f"! Material definition for Material ID {mat_id}",
    ]
    if temperature is not None:
        lines.append(f"! Evaluated at Temperature = {temperature:g} C")

    if youngs_modulus:
        lines.extend([
            f"MP,EX,{mat_id},{youngs_modulus:g}   ! User-supplied Young's Modulus (MPa)",
            f"MP,PRXY,{mat_id},0.33             ! Assumed Poisson's ratio (verify with teammate)",
            f"TB,MISO,{mat_id},1,{len(strains)} ! Multilinear Isotropic Hardening",
            f"TBTEMP,{temperature if temperature is not None else 0.0:g}",
        ])
        for eps, sig in zip(strains, stresses):
            eps_pl = max(0.0, eps - sig / youngs_modulus)
            lines.append(f"TBPT,DEFI,{eps_pl:.8e},{sig:.6f}")
    else:
        lines.extend([
            f"! NOTICE: Raw Total Strain (E11) tabular output. Requires user-confirmed linear elastic E.",
            f"TB,PLAS,{mat_id},1,{len(strains)},MISO",
            f"TBTEMP,{temperature if temperature is not None else 0.0:g}",
        ])
        for eps, sig in zip(strains, stresses):
            lines.append(f"TBPT,DEFI,{eps:.8e},{sig:.6f}")
    lines.append("! End of Material Definition\n")
    return "\n".join(lines)


def format_xml_snippet(strains, stresses, mat_name="AlSi10Mg_ML_Surrogate", youngs_modulus=None):
    """Format as an ANSYS Engineering Data XML property snippet."""
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<EngineeringData version="1.0">',
        f'  <Material name="{mat_name}">',
        '    <Description>Surrogate-predicted multiscale material response (Untested Template)</Description>',
        '    <PropertyData property="Stress-Strain">',
        '      <Data>',
    ]
    for eps, sig in zip(strains, stresses):
        strain_val = max(0.0, eps - sig / youngs_modulus) if youngs_modulus else eps
        lines.append(f'        <Point strain="{strain_val:.8e}" stress="{sig:.6f}" />')
    lines.extend([
        '      </Data>',
        '    </PropertyData>',
        '  </Material>',
        '</EngineeringData>\n'
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--temperature", type=float, required=True, help="Matrix temperature in °C (30 to 200)")
    parser.add_argument("--rate", type=float, required=True, help="Strain rate in 1/s (1e-5 to 1e-3)")
    parser.add_argument("--density", type=float, default=2700.0, help="Density (kg/m^3)")
    parser.add_argument("--G", type=float, default=25300.0, help="Shear modulus (MPa)")
    parser.add_argument("--target", default="Svm", choices=["SCAU11", "Svm"], help="Target stress component")
    parser.add_argument("--format", default="csv", choices=["csv", "apdl", "xml"], help="Output format")
    parser.add_argument("--mat-id", type=int, default=1, help="Material ID for APDL snippets")
    parser.add_argument("--youngs-modulus", type=float, default=None,
                        help="Optional Young's Modulus (MPa) to calculate plastic strain from total strain")
    parser.add_argument("--output", type=Path, help="Save generated material card to this file path")

    args = parser.parse_args()

    # Check bounds and warnings
    warns = warnings_for(args.temperature, np.log10(args.rate), args.density, args.G)
    for w in warns:
        sys.stderr.write(f"[WARNING] {w}\n")

    strains, stresses = predict_curve(args.temperature, args.rate, args.density, args.G, args.target)

    if args.format == "csv":
        content = format_tabular_csv(strains, stresses, args.youngs_modulus)
    elif args.format == "apdl":
        content = format_apdl_snippet(strains, stresses, args.mat_id, args.youngs_modulus, args.temperature)
    elif args.format == "xml":
        content = format_xml_snippet(strains, stresses, youngs_modulus=args.youngs_modulus)
    else:
        raise ValueError(f"Unknown format: {args.format}")

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content, encoding="utf-8")
        print(f"Material card written to {args.output} ({len(strains)} points, format: {args.format})")
    else:
        sys.stdout.write(content)


if __name__ == "__main__":
    main()
